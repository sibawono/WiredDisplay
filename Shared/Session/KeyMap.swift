/// USB HID keyboard usages (page 0x07, what UIKit's `UIKey.keyCode` reports)
/// to macOS virtual key codes (Carbon `kVK_*`). Positional, like a USB
/// keyboard: the Mac's own layout decides the character (Magic Keyboard on
/// the iPad, R-INP-02).
public enum KeyMap {
    public enum Modifier: Sendable, Equatable, CaseIterable {
        case control, shift, option, command
    }

    /// Valid usages carried on the wire.
    public static let usageRange: ClosedRange<UInt16> = 0x04...0xE7
    public static let capsLockUsage: UInt16 = 0x39

    public static func virtualKey(forUsage usage: UInt16) -> UInt16? { table[usage] }

    public static func modifier(forUsage usage: UInt16) -> Modifier? {
        switch usage {
        case 0xE0, 0xE4: return .control
        case 0xE1, 0xE5: return .shift
        case 0xE2, 0xE6: return .option
        case 0xE3, 0xE7: return .command
        default: return nil
        }
    }

    /// Navigation keys carry the "secondary fn" flag on a real Mac keyboard;
    /// arrows and keypad keys also carry "numeric pad". Some apps check them.
    public static func isFunctionCluster(_ usage: UInt16) -> Bool { (0x49...0x52).contains(usage) || (0x3A...0x45).contains(usage) }
    public static func isNumericPad(_ usage: UInt16) -> Bool { (0x4F...0x52).contains(usage) || (0x53...0x63).contains(usage) || usage == 0x67 }

    private static let table: [UInt16: UInt16] = [
        // Letters
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03, 0x0A: 0x05, 0x0B: 0x04,
        0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25, 0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23,
        0x14: 0x0C, 0x15: 0x0F, 0x16: 0x01, 0x17: 0x11, 0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07,
        0x1C: 0x10, 0x1D: 0x06,
        // Digits row
        0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, 0x22: 0x17, 0x23: 0x16, 0x24: 0x1A, 0x25: 0x1C,
        0x26: 0x19, 0x27: 0x1D,
        // Return, Escape, Delete, Tab, Space, punctuation
        0x28: 0x24, 0x29: 0x35, 0x2A: 0x33, 0x2B: 0x30, 0x2C: 0x31, 0x2D: 0x1B, 0x2E: 0x18, 0x2F: 0x21,
        0x30: 0x1E, 0x31: 0x2A, 0x32: 0x2A, 0x33: 0x29, 0x34: 0x27, 0x35: 0x32, 0x36: 0x2B, 0x37: 0x2F,
        0x38: 0x2C, 0x39: 0x39,
        // F1-F12
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, 0x3E: 0x60, 0x3F: 0x61, 0x40: 0x62, 0x41: 0x64,
        0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F,
        // Insert(Help), Home, Page Up, Forward Delete, End, Page Down, arrows
        0x49: 0x72, 0x4A: 0x73, 0x4B: 0x74, 0x4C: 0x75, 0x4D: 0x77, 0x4E: 0x79,
        0x4F: 0x7C, 0x50: 0x7B, 0x51: 0x7D, 0x52: 0x7E,
        // Keypad
        0x53: 0x47, 0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C, 0x59: 0x53, 0x5A: 0x54,
        0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57, 0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B, 0x61: 0x5C, 0x62: 0x52,
        0x63: 0x41, 0x67: 0x51,
        // ISO § key, F13-F20
        0x64: 0x0A, 0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A, 0x6C: 0x40, 0x6D: 0x4F, 0x6E: 0x50,
        0x6F: 0x5A,
        // JIS
        0x87: 0x5E, 0x89: 0x5D, 0x90: 0x68, 0x91: 0x66,
        // Modifiers: left/right control, shift, option, command
        0xE0: 0x3B, 0xE1: 0x38, 0xE2: 0x3A, 0xE3: 0x37, 0xE4: 0x3E, 0xE5: 0x3C, 0xE6: 0x3D, 0xE7: 0x36,
    ]

    /// Maps an ASCII character from the iPad on-screen keyboard to a USB HID usage
    /// (US layout) plus whether left Shift (0xE1) is needed.
    public static func usage(for character: Character) -> (usage: UInt16, shift: Bool)? {
        guard let scalar = character.asciiValue else { return nil }
        switch scalar {
        case 0x61...0x7A: return (UInt16(scalar - 0x61) + 0x04, false) // a-z
        case 0x41...0x5A: return (UInt16(scalar - 0x41) + 0x04, true)  // A-Z
        case 0x31...0x39: return (UInt16(scalar - 0x31) + 0x1E, false) // 1-9
        case 0x30: return (0x27, false)                                 // 0
        case 0x0A, 0x0D: return (0x28, false)                           // Return
        case 0x09: return (0x2B, false)                                 // Tab
        case 0x20: return (0x2C, false)                                 // Space
        default: break
        }
        switch character {
        case "!": return (0x1E, true)
        case "@": return (0x1F, true)
        case "#": return (0x20, true)
        case "$": return (0x21, true)
        case "%": return (0x22, true)
        case "^": return (0x23, true)
        case "&": return (0x24, true)
        case "*": return (0x25, true)
        case "(": return (0x26, true)
        case ")": return (0x27, true)
        case "-": return (0x2D, false)
        case "_": return (0x2D, true)
        case "=": return (0x2E, false)
        case "+": return (0x2E, true)
        case "[": return (0x2F, false)
        case "{": return (0x2F, true)
        case "]": return (0x30, false)
        case "}": return (0x30, true)
        case "\\": return (0x31, false)
        case "|": return (0x31, true)
        case ";": return (0x33, false)
        case ":": return (0x33, true)
        case "'": return (0x34, false)
        case "\"": return (0x34, true)
        case "`": return (0x35, false)
        case "~": return (0x35, true)
        case ",": return (0x36, false)
        case "<": return (0x36, true)
        case ".": return (0x37, false)
        case ">": return (0x37, true)
        case "/": return (0x38, false)
        case "?": return (0x38, true)
        default: return nil
        }
    }

    /// Converts typed text from the iPad on-screen keyboard into `.key` press/release events.
    public static func keyEvents(for text: String) -> [InputEvent] {
        var events: [InputEvent] = []
        for character in text {
            guard let (usage, shift) = usage(for: character) else { continue }
            if shift { events.append(.key(usage: 0xE1, down: true)) }
            events.append(.key(usage: usage, down: true))
            events.append(.key(usage: usage, down: false))
            if shift { events.append(.key(usage: 0xE1, down: false)) }
        }
        return events
    }
}
